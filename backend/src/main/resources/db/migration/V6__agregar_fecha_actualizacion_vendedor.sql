DROP CONSTRAINT IF EXISTS fk_vendedor_tipo_documento;

ALTER TABLE vendedor
DROP CONSTRAINT IF EXISTS uq_vendedor_documento;

ALTER TABLE vendedor
DROP COLUMN IF EXISTS id_tipo_documento;

ALTER TABLE vendedor
DROP COLUMN IF EXISTS numero_documento;

ALTER TABLE tienda
DROP CONSTRAINT IF EXISTS uq_tienda_vendedor;

ALTER TABLE tienda
ADD COLUMN id_documento_fiscal BIGINT;

ALTER TABLE tienda
ADD CONSTRAINT fk_tienda_documento_fiscal
    FOREIGN KEY (id_documento_fiscal)
    REFERENCES usuario_documento (id_usuario_documento);